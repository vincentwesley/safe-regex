// Generates src/unicode/casefold-data.ts from Unicode's CaseFolding.txt.
// Usage: node scripts/gen-casefold.mjs [path-or-url]   (default: Unicode 17.0.0 from unicode.org)
// Only status C (common) and S (simple) mappings are kept: that is the "simple case folding"
// the ECMAScript spec uses for Canonicalize when the u flag is set.
import { readFileSync, writeFileSync } from 'node:fs';

const VERSION = '17.0.0';
const src = process.argv[2] ?? `https://www.unicode.org/Public/${VERSION}/ucd/CaseFolding.txt`;
const text = src.startsWith('http') ? await (await fetch(src)).text() : readFileSync(src, 'utf8');

const pairs = [];
for (const line of text.split('\n')) {
  const body = line.split('#')[0].trim();
  if (!body) continue;
  const [code, status, mapping] = body.split(';').map((f) => f.trim());
  if (status !== 'C' && status !== 'S') continue;
  pairs.push([parseInt(code, 16), parseInt(mapping, 16)]);
}
pairs.sort((a, b) => a[0] - b[0]);
// Delta-encode to keep the file small: [cpDelta, foldedMinusCp, ...]
const flat = [];
let prev = 0;
for (const [cp, f] of pairs) {
  flat.push(cp - prev, f - cp);
  prev = cp;
}
const header = (text.split('\n')[0] || '').replace(/^#\s*/, '');
const out = `// GENERATED by scripts/gen-casefold.mjs from ${header} — do not edit.
// Simple case folding (status C + S), delta-encoded as [codePointDelta, foldedMinusCodePoint] pairs.
export const CASEFOLD_UNICODE_VERSION = '${VERSION}';
export const CASEFOLD_DELTAS: readonly number[] = [${flat.join(',')}];
`;
writeFileSync('src/unicode/casefold-data.ts', out);
console.log(`wrote ${pairs.length} mappings`);
